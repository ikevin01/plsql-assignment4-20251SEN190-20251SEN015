-- Drop tables if they already exist
BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE order_items CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE orders CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE products CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE customers CASCADE CONSTRAINTS';
EXCEPTION
   WHEN OTHERS THEN NULL;
END;
/

-- Customers Table
CREATE TABLE customers (
    customer_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR2(100) NOT NULL,
    email         VARCHAR2(100) UNIQUE NOT NULL,
    loyalty_tier  VARCHAR2(20) DEFAULT 'BRONZE' CHECK (loyalty_tier IN ('BRONZE', 'SILVER', 'GOLD', 'PLATINUM')),
    created_at    DATE DEFAULT SYSDATE
);

-- Products Table
CREATE TABLE products (
    product_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name  VARCHAR2(100) NOT NULL,
    unit_price    NUMBER(10,2) NOT NULL CHECK (unit_price >= 0),
    stock_qty     NUMBER(8) NOT NULL CHECK (stock_qty >= 0),
    category      VARCHAR2(50)
);

-- Orders Table
CREATE TABLE orders (
    order_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   NUMBER NOT NULL REFERENCES customers(customer_id),
    order_date    DATE DEFAULT SYSDATE,
    total_amount  NUMBER(12,2) DEFAULT 0 CHECK (total_amount >= 0),
    status        VARCHAR2(20) DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'PROCESSED', 'CANCELLED'))
);

-- Order Items Table
CREATE TABLE order_items (
    item_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      NUMBER NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id    NUMBER NOT NULL REFERENCES products(product_id),
    quantity      NUMBER(6) NOT NULL CHECK (quantity > 0),
    unit_price    NUMBER(10,2) NOT NULL CHECK (unit_price >= 0)
);

COMMIT;